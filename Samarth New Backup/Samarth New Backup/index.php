    const heroSection = document.getElementById("heroSection");

    let isVideoPlaying = false;

    // Move play overlay with mouse
    function moveOverlay(e) {
        playOverlay.style.left = `${e.pageX - 40}px`;
        playOverlay.style.top = `${e.pageY - 40}px`;
    }

    heroSection.addEventListener("mousemove", moveOverlay);

    // Toggle play/pause for background video on click
    function togglePlayPause() {
        if (!isVideoPlaying) {
            video.play();
            video.muted = false;
            playOverlay.classList.add("hide");
            heroSection.style.cursor = "auto";
            isVideoPlaying = true;
        } else {
            video.pause();
            playOverlay.classList.remove("hide");
            heroSection.style.cursor = "none";
            isVideoPlaying = false;
        }
    }

    heroSection.addEventListener("click", togglePlayPause);

    // Pause video if it's not visible
    const observer = new IntersectionObserver(
        (entries) => {
            entries.forEach((entry) => {
                if (!entry.isIntersecting && isVideoPlaying) {
                    video.pause();
                    isVideoPlaying = false;
                    playOverlay.classList.remove("hide");
                    heroSection.style.cursor = "none";
                }
            });
        },
        { threshold: 0.1 }
    );

    observer.observe(heroSection);

    // Handling hover and click functionality for grid videos
    const wrappers = document.querySelectorAll('.hover_video_wrapper');
    const iframes = document.querySelectorAll('.youtube-iframe');
    const videos = document.querySelectorAll('.hover-video');

    // Pause all videos and reset iframe and video display
    function pauseAllVideos() {
        videos.forEach(video => {
            video.pause();
            video.style.display = 'block'; // Reset HTML5 videos to be visible
        });
        iframes.forEach(iframe => {
            iframe.style.display = 'none';
            iframe.contentWindow.postMessage('{"event":"command","func":"pauseVideo","args":""}', '*');
        });
    }

    // Play/pause HTML5 video on hover
    videos.forEach(video => {
        video.addEventListener('mouseover', function() {
            video.play();
        });
        video.addEventListener('mouseout', function() {
            video.pause();
        });
    });

    // Toggle between HTML5 video and YouTube iframe on click
    wrappers.forEach(wrapper => {
        wrapper.addEventListener('click', function() {
            pauseAllVideos(); // Pause all currently playing videos

            const video = wrapper.querySelector('.hover-video');
            const iframe = wrapper.querySelector('.youtube-iframe');

            // Show the YouTube iframe for the clicked wrapper
            video.style.display = 'none';
            iframe.style.display = 'block';
            iframe.contentWindow.postMessage('{"event":"command","func":"playVideo","args":""}', '*');
        });
    });

    // Load YouTube IFrame API script if not already loaded
    if (!window.YT) {
        const tag = document.createElement('script');
        tag.src = "https://www.youtube.com/iframe_api";
        document.head.appendChild(tag);
    }

    // Initialize YouTube players when API is ready
    window.onYouTubeIframeAPIReady = function() {
        iframes.forEach(iframe => {
            new YT.Player(iframe, {
                events: {
                    'onReady': function() {
                        iframe.setAttribute("data-player-loaded", "true");
                    }
                }
            });
        });
    };
});

